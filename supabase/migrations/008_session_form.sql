-- ════════════════════════════════════════════════════════════════════
-- 008: 세션마다 검사 당시의 양식 — sessions.form_id
--
-- 왜: 검사지가 학년만이 아니라 **학기**로도 갈린다(1·2학년 2학기 문항, 담당자 2026-10-19 배포).
-- 지금까지는 화면·채점·결과보고서가 학년만 보고 양식을 매번 다시 골랐고, 점수는 양식의 자리 번호
-- 코드(rw01…)로 쌓인다. 학기 양식이 생긴 뒤에도 그렇게 고르면 이미 끝난 검사가 다른 낱말로 다시
-- 그려지고 다른 기준으로 판정된다. 그래서 세션을 만들 때 양식을 정해 행에 적는다(학급 정보를
-- 비정규화 복사하는 것과 같은 이유 — 검사 당시 값을 유지한다). 값은 lib/forms의 `SurveyForm.id`.
--
-- null = 이 컬럼이 생기기 전에 만든 세션 = **학년만으로 양식을 고르던 때의 세션**이다
-- (lib/forms `formOfSession`이 옛 규칙 `formForGrade`로 읽는다). 아래에서 기존 행을 채우지만,
-- 이 SQL을 실행한 뒤 새 코드가 배포되기 전까지 옛 코드가 만드는 세션도 null로 들어오므로 null을 허용한다.
-- 그 세션들도 옛 규칙의 문항으로 검사했으니 null로 읽는 것이 맞다.
--
-- ⚠️ 적용 순서: **이 SQL을 코드 배포보다 먼저 실행할 것.** 새 코드는 목록·결과지·제출·업로드에서 이
-- 컬럼을 읽는다. 컬럼만 먼저 있는 것은 무해하다(지금 코드는 이 컬럼을 모른다).
-- 재실행 안전: 컬럼이 있으면 건너뛰고, 채우기는 null인 행만 건드린다.
-- ════════════════════════════════════════════════════════════════════

alter table sessions add column if not exists form_id text;

-- 기존 세션 = 학년만으로 고르던 양식(2학년 → KODYS-G2, 그 밖 → KODYS-G1 — 3~6학년은 G1 폴백이었다)
update sessions set form_id = case when grade = 2 then 'KODYS-G2' else 'KODYS-G1' end
where form_id is null;

-- PostgREST 스키마 캐시를 바로 갱신한다(006 참고 — 없으면 수 분간 새 컬럼 조회가 500).
notify pgrst, 'reload schema';
