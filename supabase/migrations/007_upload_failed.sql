-- 007: 녹음 「저장 실패」 표시 — sessions.upload_failed
--
-- 왜: 아이가 읽었는데 인터넷 문제로 녹음이 서버에 올라가지 않은 문항은 지금까지 다른 미녹음
-- (「모르겠어요」로 넘긴 것·빠뜨린 것)과 구별되지 않았다. 채점은 그대로 둔다 — 셋 다 오반응
-- (X · 0점 · 문장은 제한 시간)으로 고정된다(lib/scoring withUnrecordedFixed). 관리자 결과지가
-- 「기술 문제로 빠진 문항」을 알아볼 수 있게 **표시만** 더한다(사용자 확정 2026-10-08, 담당자 회신
-- 아님 — 결과보고서 PDF 표기는 담당자 양식이라 넣지 않았다).
--
-- 값: 검사 기기가 녹음을 시도했다고 적은 페이지 코드 가운데, **제출 순간 서버에 녹음이 하나도 없는 것.**
-- 제출 라우트가 한 번 계산해 제출 확정과 같은 업데이트로 적는다 — 제출된 검사는 업로드가 잠겨
-- 녹음이 나중에 생기지 않으므로 다시 계산할 일이 없다. 도입 전 검사는 빈 배열(알 수 없음 = 표시 없음).
--
-- ⚠️ 적용 순서: **이 SQL을 코드 배포보다 먼저 실행할 것.** 새 코드는 목록·결과지·제출에서 이 컬럼을
-- 읽고 쓴다. 컬럼만 먼저 있는 것은 무해하다(지금 코드는 이 컬럼을 모른다).
-- 재실행 안전: 이미 있으면 건너뛴다.
-- ════════════════════════════════════════════════════════════════════

alter table sessions add column if not exists upload_failed text[] not null default '{}';

