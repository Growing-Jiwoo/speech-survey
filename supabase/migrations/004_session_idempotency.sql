-- 004: 세션 생성 멱등 키 (사용자 확정 2026-08-21)
--
-- 왜: 시작 화면의 [맞아요, 시작하기]가 연타·재전송되면 같은 아동의 세션이 두 개
-- 만들어진다. 화면은 `busy`로 버튼을 잠그지만 그건 **클라이언트 방어뿐**이고,
-- 서버에는 같은 요청을 두 번 받았는지 판정할 근거가 없었다(E2E 2026-08-20 항목 3.17).
--
-- 왜 시간 창(예: "최근 30초 내 같은 학급·번호면 거부")이 아닌가:
-- 이 앱은 **재검사를 의도적으로 허용한다** — 시작 화면이 "이미 검사했어요"로 경고만
-- 하고 [네, 다시 검사할게요]로 통과시킨다(스펙 "중복 검사 경고"). 그리고 정상 재검사가
-- 실제로 짧은 간격으로 일어난다: 마이크가 안 잡혀 나갔다 다시 시작하거나, 아이가 울어
-- 중단하고 달래서 다시 시작하는 경우다. 시간 창을 두면 그 정상 흐름이 막히고, 검사자는
-- 이어갈 수도 없는 "방금 시작한 검사가 있어요"를 보게 된다 — **막다른 길이 새로 생긴다.**
-- 실패 방향이 중요하다: 멱등 키가 실패하면 세션이 하나 더 생기고(오늘과 같다) 관리자가
-- 지우면 되지만, 시간 창이 오작동하면 **현장에서 검사를 시작할 수 없다.**
--
-- 멱등 키는 "같은 사용자 의도 = 같은 키"를 정확히 표현한다. 확인 모달을 열 때 한 번
-- 만들어지므로 연타·재전송은 같은 키를 재사용하고(→ 첫 세션을 그대로 돌려준다),
-- 모달을 다시 여는 정상 재검사는 새 키를 얻는다(→ 새 세션이 만들어진다).
-- 이 저장소는 같은 문제를 이미 같은 방식으로 풀었다 — `approveClassCode`가 시간 창이
-- 아니라 `.eq('status','pending')` 한 방으로 "내가 첫 호출인지"를 판정한다(lib/db.ts).
--
-- ⚠️ 적용 순서: **이 SQL을 코드 배포보다 먼저 실행할 것.** 새 코드는 세션을 만들 때
-- `idem_key`를 함께 보내므로, 컬럼이 없는 DB에 새 코드가 붙으면 PostgREST가 그 삽입을
-- 거부해 **모든 검사 시작이 실패한다**(현장에서 아무도 검사를 시작할 수 없다).
-- 되돌릴 때도 순서가 반대다 — 코드를 먼저 되돌리고 그 다음 컬럼을 지운다.
-- ════════════════════════════════════════════════════════════════════

-- nullable + unique: 도입 전 행과 키를 보내지 않는 요청(있으면)을 막지 않는다.
-- Postgres의 unique 인덱스는 NULL을 서로 다른 값으로 취급하므로 null 행은 몇 개든 공존한다.
alter table sessions add column idem_key text;

-- 부분 인덱스로 둔다 — null 행이 인덱스를 차지할 이유가 없다.
create unique index sessions_idem_key_uniq on sessions(idem_key) where idem_key is not null;
