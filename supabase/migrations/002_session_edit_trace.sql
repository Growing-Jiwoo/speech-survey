-- 아동 정보 수정 이력 (사용자 확정 2026-08-15)
--
-- 검사자가 아동 번호·이름을 잘못 입력한 세션을 관리자가 고칠 수 있게 하면서,
-- **처음 들어온 값이 무엇이었는지**를 남긴다. 이게 없으면 임상 기록이 다른 아이에게
-- 조용히 넘어가도 아무도 알 수 없다(번호 오타 하나로 3번 아이의 기록이 13번 아이 것이 된다).
--
-- "누가" 고쳤는지는 남기지 않는다 — 관리자가 단일 비밀번호라 특정이 불가능한데,
-- 흉내만 낸 감사 기록은 없느니만 못한 거짓 확신을 준다. 행위자 추적이 필요해지면
-- 관리자 계정 분리가 선행돼야 한다.
--
-- 001_init.sql을 고치지 않고 새 파일로 두는 이유: 실행 이력을 DB가 기억하지 않으므로
-- 이미 실행한 파일을 고쳐도 기존 DB에는 반영될 길이 없다(supabase/migrations/README.md).
-- 새로 만드는 DB는 001 → 002 순서로 실행한다.
-- ════════════════════════════════════════════════════════════════════

alter table sessions
  -- 최초 수정 시각. null이면 한 번도 고치지 않은 세션이다.
  add column edited_at timestamptz,
  -- 최초 수정 **직전**의 아동 식별값 {child_no, child_name, gender, birth_ymd}.
  -- 두 번째 수정부터는 덮어쓰지 않는다 — 알고 싶은 것은 "처음 들어온 값"이지 중간 단계가 아니다.
  -- 같은 아동의 값이 같은 행에 남을 뿐이라 PII 노출 범위는 늘지 않는다(세션 삭제 시 함께 사라진다).
  add column original_identity jsonb;
