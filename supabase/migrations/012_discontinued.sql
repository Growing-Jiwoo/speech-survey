-- 012_discontinued.sql — 검사지 중단 규칙 ①이 적용된 세션 표시.
--
-- 검사지: "의미 낱말 첫 3개 연속 오반응 시 문장 읽기유창성 과제와 낱말 쓰기 과제를 실시하지 않습니다."
-- 이 경우 문장·낱말 쓰기는 아예 실시되지 않으므로, 전체 프로토콜을 분모로 진행률을 재면
-- 규칙대로 정상 종료된 검사가 영원히 "미완료"로 남는다. 운영자가 "규칙대로 끝난 검사"와
-- "하다 만 검사"를 구분할 수 없다.
--
-- 왜 컬럼으로 남기는가 — 현장 채점(reading_marks)에서 매번 다시 판정할 수도 있지만,
-- 그 값은 나중에 관리자가 채점을 고치면 뒤집힌다(rw01을 O로 정정하는 순간 "중단 안 됨"이 된다).
-- 중단은 검사 당시에 실제로 일어난 사실이므로 그 시점에 한 번 기록하고 이후 바꾸지 않는다.
alter table sessions add column if not exists discontinued_at timestamptz;

comment on column sessions.discontinued_at is
  '검사지 중단 규칙 ①(의미 낱말 첫 3개 연속 오반응)으로 문장·낱말 쓰기를 실시하지 않은 시각. 제출 시점에 확정되며 이후 채점 수정에 영향받지 않는다.';

-- 목록 화면이 진행률 분모를 고르는 데 쓴다(전체 조회 후 메모리 집계라 인덱스는 두지 않는다).
