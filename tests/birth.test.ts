// 생년월일 정규화 — 실제로 들어올 표기를 고정한다.
// 케이스 목록은 브라우저 프로토타입에서 실행해 확인한 것이며(2026-08-18),
// 형식이 하나라도 깨지면 교사가 명단 파일을 올리지 못하므로 회귀 핀으로 남긴다.
import { describe, expect, it } from 'vitest'
import { normBirth, toYymmdd } from '@/lib/birth'

// 두 자리 연도 해석이 실행 연도에 의존하므로 테스트는 기준 연도를 고정한다
const NOW = 2026

describe('normBirth — 구분자 없는 표기', () => {
  it.each([
    ['19960509', '1996-05-09'],
    ['960509', '1996-05-09'],
    ['20190509', '2019-05-09'],
    ['190509', '2019-05-09'],
  ])('%s → %s', (input, want) => {
    expect(normBirth(input, NOW)).toBe(want)
  })
})

describe('normBirth — 구분자 있는 표기', () => {
  it.each([
    ['1996-05-09', '1996-05-09'],
    ['96-05-09', '1996-05-09'],
    ['96-5-9', '1996-05-09'],          // 자릿수를 안 맞춘 경우
    ['2019-05-09', '2019-05-09'],
    ['2019-5-9', '2019-05-09'],
    ['19-5-9', '2019-05-09'],
    ['2019.05.09', '2019-05-09'],
    ['2019.5.9', '2019-05-09'],
    ['2019. 5. 9.', '2019-05-09'],     // 한국 엑셀 기본 표시 형식
    ['2019/05/09', '2019-05-09'],
    ['2019/5/9', '2019-05-09'],
    ['19.5.9', '2019-05-09'],
    ['2019 05 09', '2019-05-09'],
    ['2019년 5월 9일', '2019-05-09'],
    ['2019년05월09일', '2019-05-09'],
    ['  2019-05-09  ', '2019-05-09'],
  ])('%s → %s', (input, want) => {
    expect(normBirth(input, NOW)).toBe(want)
  })
})

describe('normBirth — 엑셀 날짜 일련번호', () => {
  it('43528 → 2019-03-04 (엑셀이 날짜 셀을 숫자로 저장한 경우)', () => {
    expect(normBirth('43528', NOW)).toBe('2019-03-04')
  })
  it('일련번호 범위 밖의 5자리는 날짜로 보지 않는다', () => {
    expect(normBirth('12345', NOW)).toBeNull()
  })
})

describe('normBirth — 거부해야 하는 값', () => {
  it.each([
    ['5/9/2019', '월·일 순서를 알 수 없다'],
    ['2019-02-30', '달력에 없는 날'],
    ['2019-13-45', '월·일 범위 밖'],
    ['2030-01-01', '미래'],
    ['2019-05', '조각이 둘뿐'],
    ['모름', '숫자가 없다'],
    ['', '빈 값'],
  ])('%s — %s', input => {
    expect(normBirth(input, NOW)).toBeNull()
  })
  it('null·undefined도 안전하게 null', () => {
    expect(normBirth(null, NOW)).toBeNull()
    expect(normBirth(undefined, NOW)).toBeNull()
  })
})

describe('두 자리 연도 — "생일은 미래일 수 없다"', () => {
  it('올해까지는 2000년대로 읽는다', () => {
    expect(normBirth('260509', 2026)).toBe('2026-05-09')
  })
  it('[REGRESSION] 내년이 되는 두 자리는 1900년대로 읽는다', () => {
    expect(normBirth('270509', 2026)).toBe('1927-05-09')
  })
  it('[REGRESSION] 기준 연도가 바뀌면 해석도 따라간다 — 고정 기준값을 쓰지 않는다', () => {
    expect(normBirth('270509', 2027)).toBe('2027-05-09')
  })
})

describe('toYymmdd — DB 저장 형식', () => {
  it('YYYY-MM-DD를 6자리로 줄인다', () => {
    expect(toYymmdd('2019-03-04')).toBe('190304')
  })
  it('DB 제약(char(6), 숫자 6자리)을 만족한다', () => {
    expect(toYymmdd(normBirth('2019. 5. 9.', NOW)!)).toMatch(/^[0-9]{6}$/)
  })
})
